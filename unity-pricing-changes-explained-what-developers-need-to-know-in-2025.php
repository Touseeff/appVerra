                    <h2 class="heading55px darkpurple">What Are the 2025 Unity Pricing Changes?</h2>
                    <ul class="list">
                        <li>Unity has cancelled the Runtime Fee, effective immediately. This means no more install-based fees tied to game downloads regardless of version, including Unity 6.</li>
                        <li>Subscription remains seat-based. Pricing updates for the Pro and Enterprise tiers take effect January 1, 2025 — for new, renewed, or upgraded subscriptions.</li>
                        <li>Unity Personal remains free, with more generous eligibility: revenue & funding cap raised from $100,000 to $200,000 USD. Also, for projects using Unity 6, the “Made with Unity” splash screen becomes optional.</li>
                        <li>Unity Pro subscription sees an 8% price increase, to $2,200 per seat per year.</li>
                        <li>Unity Enterprise pricing increases by 25%, with custom pricing for large organizations (especially those with over $25 million USD in annual revenue and funding).</li>
                    </ul>
                </section>

                <section id="section3">
                    <h2 class="heading55px darkpurple">Why Unity Changed Its Pricing Model</h2>
                    <p>In 2023, Unity proposed a runtime fee: a per-install fee to kick in when games reached certain revenue and install thresholds. This sparked strong backlash around unpredictability, “ghost installs”, and risk to small / indie dev budgets.</p>
                    <p>Unity heard the community: after feedback, concerns and public critique, they cancelled the runtime fee. They acknowledged that the fee model conflicted with developers’ expectations and the ethos of democratizing game creation.</p>
                    <p>Their goal now: maintain a sustainable revenue model, regain trust, offer clarity, and ensure tools keep getting improved. Seat-based pricing and annual reviews give more predictability for devs and Unity alike.</p>
