                <section id="section3">
                    <h2 class="heading55px darkpurple">Tools & Frameworks for AI React Native Integration</h2>
                    <p><strong>The real magic happens when you choose the right tools. Here are the top frameworks:</strong></p>
                    <ul class="list">
                        <li><strong>TensorFlow.js (React Native tutorial approach)</strong>  
                        Ideal for running ML models in JavaScript. Lightweight, flexible, and community-driven.  
                        Mini Example: To integrate TensorFlow.js, install @tensorflow/tfjs and use pre-trained models for tasks like image recognition within your React Native app.</li>
                        <li><strong>TensorFlow Lite & Core ML  </strong>
                        These enable on-device machine learning in React Native, ensuring offline performance and reduced latency.</li>
                        <li><strong>Dialogflow / Rasa</strong>  
                        Best for creating conversational AI like chatbots and voice assistants.</li>
                        <li><strong>OpenAI API</strong>  
                        Great for natural language understanding, text generation, or smart Q&A.</li>
                        <li><strong>Firebase ML Kit</strong>  
                        Google’s SDK for features like barcode scanning, text recognition, and image labeling.</li>
                    </ul>
